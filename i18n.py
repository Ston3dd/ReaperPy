class Translator:
    def __init__(self, lang="de"):
        self.lang = lang if lang in STRINGS else "de"
        self._bindings = []

    def bind(self, widget, attr, key):
        """Widget mit einem i18n-Key verknüpfen – wird bei Sprachwechsel neu gesetzt."""
        self._bindings.append((widget, attr, key))
        self._apply(widget, attr, key)

    def set_lang(self, lang):
        if lang not in STRINGS:
            return
        self.lang = lang
        for w, a, k in self._bindings:
            try:
                self._apply(w, a, k)
            except Exception:
                pass

    def _apply(self, widget, attr, key):
        try:
            widget.configure(**{attr: self.t(key)})
        except Exception:
            pass

    def t(self, key, **kw):
        s = STRINGS[self.lang].get(key, key)
        if kw:
            try:
                return s.format(**kw)
            except Exception:
                return s
        return s